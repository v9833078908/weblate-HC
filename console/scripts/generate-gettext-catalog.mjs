import { readdir, readFile, writeFile } from "node:fs/promises";

const sourceRoot = new URL("../src/", import.meta.url);
const catalogPath = new URL("../src/gettext-catalog.js", import.meta.url);
const translationCall = /\bt\(\s*("(?:\\.|[^"\\])*")\s*,?\s*\)/gs;

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) =>
    left.name.localeCompare(right.name),
  )) {
    const path = new URL(entry.name, directory);
    if (entry.isDirectory()) {
      files.push(...(await sourceFiles(new URL(`${entry.name}/`, directory))));
    } else if (
      /\.tsx?$/.test(entry.name) &&
      !entry.name.includes(".test.") &&
      entry.name !== "generated.ts"
    ) {
      files.push(path);
    }
  }
  return files;
}

const messages = new Set();
for (const path of await sourceFiles(sourceRoot)) {
  const source = await readFile(path, "utf8");
  for (const match of source.matchAll(translationCall)) {
    messages.add(JSON.parse(match[1]));
  }
}

if (messages.size === 0) {
  throw new Error("No Producer Console gettext messages were found.");
}

const output = [
  "// Copyright © HCGameLoc",
  "//",
  "// SPDX-License-Identifier: GPL-3.0-or-later",
  "",
  "// Generated by scripts/generate-gettext-catalog.mjs. Do not edit.",
  ...[...messages]
    .sort()
    .map((message) => `gettext(${JSON.stringify(message)});`),
  "",
].join("\n");

await writeFile(catalogPath, output, "utf8");
