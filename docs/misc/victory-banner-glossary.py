def family(key: str) -> str:
    for prefix, name in FAMILIES:
        if key.startswith(prefix):
            return name
    msg = f"no family for key {key!r}"
    raise ValueError(msg)


def name_family(key: str, index: int) -> str:
    if key.startswith("LastName_"):
        if index < RU_MALE_SURNAMES:
            return "surname_ru_m"
        if index < RU_MALE_SURNAMES + RU_FEMALE_SURNAMES:
            return "surname_ru_f"
        return "surname_de"
    if index < RU_MALE_NAMES:
        return "name_ru_m"
    if index < RU_MALE_NAMES + RU_FEMALE_NAMES:
        return "name_ru_f"
    return "name_de_m"


