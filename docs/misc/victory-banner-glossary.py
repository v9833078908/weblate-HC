def read_kit(path: Path) -> list[tuple[str, str | None, str, str, str]]:
    """Return (section, subsection, key, ru, en) for every real term row."""
    _sheet, rows = next(iter(read_sheets(path).items()))
    header = [cell.strip() for cell in rows[0]]
    if header != ["ID \\ LANGID", "COMMENTS", "RU", "EN"]:
        msg = f"unexpected kit header: {header!r}"
        raise ValueError(msg)
    out = []
    section: str | None = None
    subsection: str | None = None
    for row in rows[1:]:
        key, comment, ru, en = (cell.strip() for cell in row)
        if not any((key, comment, ru, en)):
            continue
        if not key and comment and not ru and not en:
            section, subsection = comment, None
            continue
        if key.startswith("#") and not ru and not en:
            subsection = key.lstrip("# ").strip()
            continue
        out.append((section, subsection, key, ru, en))
    return out


def build(kit: Path, out: Path) -> None:
    rows = read_kit(kit)
    selected: dict[str, dict] = {}
    name_index = {"Name_": 0, "LastName_": 0}

    for section, subsection, key, ru, en in rows:
        is_name = key.startswith(NAME_PREFIXES)
        is_core = key.startswith(CORE_PREFIXES) and not key.endswith("Desc")
        if key in DROP_KEYS or not (is_name or is_core):
            continue
        if is_name:
            prefix = "Name_" if key.startswith("Name_") else "LastName_"
            fam = name_family(key, name_index[prefix])
            name_index[prefix] += 1
        else:
            fam = family(key)

        target = "" if key in BLANK_EN_KEYS or key in GERMAN_NAME_FIX else en
        if target.lower() in {"on", "off"} or RAW_ABBREV.search(target):
            target = ""

        entry = selected.get(ru)
        if entry is None:
            note_extra = []
            if key in GERMAN_NAME_FIX:
                note_extra.append(
                    "en-ячейка кита содержит транслитерацию с русского "
                    f"({en}) вместо немецкого написания ({GERMAN_NAME_FIX[key]}) — "
                    "оставлена пустой"
                )
            selected[ru] = {
                "target": target,
                "family": fam,
                "keys": [key],
                "section": section,
                "subsection": subsection,
                "name_meaning": name_meaning(fam) if is_name else None,
                "generated": note_extra,
            }
            continue
        entry["keys"].append(key)
        if not entry["target"] and target:
            entry["target"] = target

    missing = [
        ru
        for ru, data in selected.items()
        if data["name_meaning"] is None and ru not in MEANING
    ]
    if missing:
        msg = f"no meaning written for {missing!r}"
        raise ValueError(msg)

    with out.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["ru", "en", "note"])
        for ru, data in selected.items():
            meaning = data["name_meaning"] or MEANING[ru]
            parts = [meaning, RULES[data["family"]]]
            parts.extend(data["generated"])
            if extra := EXTRA.get(ru):
                parts.append(extra)
            note = ". ".join(parts) + "."
            note += " Ключ движка: " + ", ".join(data["keys"]) + "."
            where = data["section"]
            if data["subsection"]:
                where += f" / {data['subsection']}"
            note += f" Раздел: {where}."
            writer.writerow([ru, data["target"], note])

    print(f"{out}: {len(selected)} terms")
    empty = sum(1 for data in selected.values() if not data["target"])
    print(f"empty en: {empty}")


if __name__ == "__main__":
    build(Path(sys.argv[1]), Path(sys.argv[2]))
